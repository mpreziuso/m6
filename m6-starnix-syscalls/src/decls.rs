// -- Syscall declaration

// `ArchWidth` is canonical in `starnix_types::arch` (mirrors upstream
// `use starnix_types::arch::ArchWidth;`). Re-export it so callers that mix
// `starnix_syscalls::decls::ArchWidth` and `starnix_types::arch::ArchWidth`
// resolve to the SAME type.
pub use starnix_types::arch::ArchWidth;

/// A particular invocation of a system call.
pub struct Syscall {
    pub decl: SyscallDecl,
    pub arg0: SyscallArg,
    pub arg1: SyscallArg,
    pub arg2: SyscallArg,
    pub arg3: SyscallArg,
    pub arg4: SyscallArg,
    pub arg5: SyscallArg,
}

impl core::fmt::Debug for Syscall {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(
            f,
            "{:?}({:#x}, {:#x}, {:#x}, {:#x}, {:#x}, {:#x})",
            self.decl, self.arg0, self.arg1, self.arg2, self.arg3, self.arg4, self.arg5
        )
    }
}

/// A system call declaration (number + architecture width).
#[derive(Copy, Clone)]
pub struct SyscallDecl {
    pub number: u64,
    pub arch_width: ArchWidth,
}

impl SyscallDecl {
    pub fn from_number(number: u64, arch_width: ArchWidth) -> SyscallDecl {
        Self { arch_width, number }
    }

    pub fn name(&self) -> &'static str {
        // Placeholder — will be wired to linux_uapi __NR_* constants
        // once m6-starnix-uapi is integrated.
        "<syscall>"
    }
}

impl core::fmt::Debug for SyscallDecl {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "{}:{}", self.name(), self.number)
    }
}
